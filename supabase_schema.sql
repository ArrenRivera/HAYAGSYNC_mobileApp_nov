create or replace function public.guard_report_inserts()
returns trigger language plpgsql security definer set search_path = public, auth
as $$
declare
  profile_name text;
begin
  if public.current_app_role() = 'parent' then
    select u.name into profile_name from public.users u where u.id = public.current_profile_id();
    if new.student_id is not null then
      select s.name, s.grade, s.section
      into new.student_name, new.student_grade, new.student_section
      from public.students s
      where s.id = new.student_id and s.parent_id = public.current_profile_id();
    end if;
    new.parent_id := public.current_profile_id();
    new.parent_name := coalesce(profile_name, 'Parent');
    new.reporter_id := auth.uid()::text;
    new.reporter_name := coalesce(profile_name, 'Parent');
    new.report_source := 'Parent-Reported';
    new.status := 'Pending';
    new.appeal_count := 0;
    new.discipline_action := null;
    new.discipline_notes := null;
    new.escalation_reason := null;
    new.escalation_notes := null;
    new.escalated_to := null;
    new.board_findings := null;
    new.board_decision := null;
    new.punishment_imposed := null;
    new.president_notes := null;
  end if;
  return new;
end;
$$;
drop trigger if exists guard_report_inserts_trigger on public.reports;
create trigger guard_report_inserts_trigger before insert on public.reports
for each row execute procedure public.guard_report_inserts();

create or replace function public.guard_parent_report_updates()
returns trigger language plpgsql set search_path = public, auth
as $$
begin
  if public.current_app_role() = 'parent' then
    if (to_jsonb(new) - 'status' - 'appealed_reason' - 'appeal_count' - 'updated_at') is distinct from
       (to_jsonb(old) - 'status' - 'appealed_reason' - 'appeal_count' - 'updated_at') then
      raise exception 'Parents may only update appeal fields.';
    end if;
    if new.status <> 'appealed' or new.appeal_count <> old.appeal_count + 1 or
       nullif(trim(new.appealed_reason), '') is null then
      raise exception 'Parents may only submit a new appeal.';
    end if;
  end if;
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists guard_parent_report_updates_trigger on public.reports;
create trigger guard_parent_report_updates_trigger before update on public.reports
for each row execute procedure public.guard_parent_report_updates();

