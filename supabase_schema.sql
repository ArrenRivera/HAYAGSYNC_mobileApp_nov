create table if not exists public.users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid,
  email text not null unique,
  name text not null,
  role text not null default 'parent' check (role in (
    'parent', 'adviser', 'principal', 'ministrong_tagasubaybay', 'osd',
    'board_of_discipline', 'school_president'
  )),
  avatar_url text,
  assigned_section text,
