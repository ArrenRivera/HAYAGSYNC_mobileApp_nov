create policy meetings_insert_staff on public.meetings for insert to authenticated
with check (public.is_staff());
create policy meetings_update_staff on public.meetings for update to authenticated
using (public.is_staff()) with check (public.is_staff());
create policy meetings_delete_staff on public.meetings for delete to authenticated using (public.is_staff());

create policy chat_select_report_access on public.chat_messages for select to authenticated
using (exists (select 1 from public.meetings m where m.id = meeting_id and public.can_access_report(m.report_id)));
create policy chat_insert_sender_access on public.chat_messages for insert to authenticated
with check (
  sender_id = public.current_profile_id() and
  exists (select 1 from public.meetings m where m.id = meeting_id and public.can_access_report(m.report_id))
);
create policy chat_update_report_access on public.chat_messages for update to authenticated
using (exists (select 1 from public.meetings m where m.id = meeting_id and public.can_access_report(m.report_id)))
with check (exists (select 1 from public.meetings m where m.id = meeting_id and public.can_access_report(m.report_id)));

