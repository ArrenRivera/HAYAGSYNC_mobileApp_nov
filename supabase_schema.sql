create or replace function public.current_profile_id()
returns bigint
language sql stable security definer
set search_path = public, auth
as $$
  select u.id from public.users u where u.auth_user_id = auth.uid() limit 1
$$;

create or replace function public.current_app_role()
returns text
language sql stable security definer
set search_path = public, auth
as $$
  select u.role from public.users u where u.auth_user_id = auth.uid() limit 1
$$;

create or replace function public.is_staff()
returns boolean
language sql stable security definer
set search_path = public, auth
as $$
  select coalesce(public.current_app_role() in (
    'adviser', 'principal', 'ministrong_tagasubaybay', 'osd',
    'board_of_discipline', 'school_president'
  ), false)
$$;

create or replace function public.can_access_report(p_report_id bigint)
returns boolean
language sql stable security definer
set search_path = public, auth
as $$
  select public.is_staff() or exists (
    select 1
    from public.reports r
    where r.id = p_report_id
      and (
        r.parent_id = public.current_profile_id()
        or exists (
          select 1 from public.students s
          where s.id = r.student_id and s.parent_id = public.current_profile_id()
        )
      )
  )
$$;

create or replace function public.create_parent_profile()
returns trigger
language plpgsql security definer
set search_path = public, auth
as $$
declare
  profile_id bigint;
  existing_role text;
  existing_auth_id uuid;
  first_child jsonb;
  child jsonb;
begin
  select u.id, u.role, u.auth_user_id
  into profile_id, existing_role, existing_auth_id
  from public.users u
  where lower(u.email) = lower(coalesce(new.email, ''))
  limit 1;

  if found then
    -- Existing staff roles are linked only by an administrator.
    if existing_role <> 'parent' then
      return new;
    end if;
    if existing_auth_id is not null and existing_auth_id <> new.id then
      raise exception 'This profile is already linked to another Auth user.';
    end if;
    if exists (
      select 1 from information_schema.columns
      where table_schema = 'public' and table_name = 'users' and column_name = 'password'
    ) then
      execute 'update public.users set auth_user_id = $1, password = null where id = $2'
        using new.id, profile_id;
    else
      update public.users set auth_user_id = new.id where id = profile_id;
    end if;
  else
    first_child := coalesce(new.raw_user_meta_data -> 'initial_students' -> 0, '{}'::jsonb);
    insert into public.users (auth_user_id, email, name, role, student_name, student_grade, student_section, academic_year)
    values (
      new.id,
      coalesce(new.email, ''),
      coalesce(new.raw_user_meta_data ->> 'name', 'Parent'),
      'parent',
      nullif(first_child ->> 'studentName', ''),
      nullif(first_child ->> 'gradeLevel', ''),
      nullif(first_child ->> 'sectionName', ''),
      nullif(first_child ->> 'academicYear', '')
    ) returning id into profile_id;
  end if;

  for child in
    select value from jsonb_array_elements(coalesce(new.raw_user_meta_data -> 'initial_students', '[]'::jsonb))
  loop
    if nullif(child ->> 'studentName', '') is not null and not exists (
      select 1 from public.students s
      where s.parent_id = profile_id
        and lower(s.name) = lower(child ->> 'studentName')
        and lower(s.section) = lower(coalesce(child ->> 'sectionName', ''))
    ) then
      if exists (
        select 1 from public.students s
        where lower(s.name) = lower(child ->> 'studentName')
      ) then
        insert into public.duplicate_flags (email, name, student_name, reason, status)
        values (
          coalesce(new.email, ''),
          coalesce(new.raw_user_meta_data ->> 'name', 'Parent'),
          child ->> 'studentName',
          'Student name already appears in another enrollment. Staff review is required.',
          'Pending'
        );
      end if;
      insert into public.students (parent_id, name, grade, section, academic_year)
      values (
        profile_id,
        child ->> 'studentName',
        coalesce(child ->> 'gradeLevel', ''),
        coalesce(child ->> 'sectionName', ''),
        coalesce(child ->> 'academicYear', '')
      );
    end if;
  end loop;
  return new;
end;
$$;

