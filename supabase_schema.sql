  select s.* from public.students s
  where public.parent_has_student_access(s.id)
  order by s.name
$$;

create or replace function public.link_child_guardian(
  p_student_id bigint,
  p_guardian_email text
) returns text
language plpgsql security definer
set search_path = public, auth
as $$
declare
  profile_id bigint := public.current_profile_id();
  guardian_id bigint;
  clean_email text := lower(btrim(p_guardian_email));
  existing_count integer;
begin
  if auth.uid() is null or public.current_app_role() <> 'parent' then
    raise exception 'Only a signed-in parent can share child access.';
  end if;
  if not exists (
    select 1 from public.students s
    where s.id = p_student_id and s.parent_id = profile_id
  ) then
    raise exception 'Only the primary linked parent can add another guardian.';
  end if;
  if clean_email = '' or clean_email = (
    select lower(email) from public.users where id = profile_id
  ) then
    raise exception 'Enter a different parent or guardian email address.';
  end if;

  select u.id into guardian_id
  from public.users u
  where lower(u.email) = clean_email
    and u.role = 'parent'
    and u.auth_user_id is not null
  limit 1;
  if guardian_id is null then
    raise exception 'No parent account uses this email yet. Ask the other guardian to register first.';
  end if;
  if exists (
    select 1 from public.student_guardians g
    where g.student_id = p_student_id and g.guardian_profile_id = guardian_id
  ) then
    return 'This parent account already has access.';
  end if;

  select count(*) into existing_count from public.student_guardians
  where student_id = p_student_id;
  if existing_count >= 1 then
    raise exception 'Only one additional parent or guardian account can be linked to this child.';
  end if;

  insert into public.student_guardians (student_id, guardian_profile_id, added_by)
  values (p_student_id, guardian_id, profile_id);
  return 'Parent account linked successfully.';
end;
$$;

create or replace function public.get_child_guardians(p_student_id bigint)
returns table (email text, guardian_name text, linked_at timestamptz)
language plpgsql stable security definer
set search_path = public, auth
as $$
begin
  if not exists (
    select 1 from public.students s
    where s.id = p_student_id and s.parent_id = public.current_profile_id()
  ) then
    raise exception 'Only the primary linked parent can manage guardian access.';
  end if;
  return query
    select u.email, u.name, g.created_at
    from public.student_guardians g
    join public.users u on u.id = g.guardian_profile_id
    where g.student_id = p_student_id
    order by g.created_at;
end;
$$;

create or replace function public.unlink_child_guardian(
  p_student_id bigint,
  p_guardian_email text
) returns void
language plpgsql security definer
set search_path = public, auth
as $$
begin
  if not exists (
    select 1 from public.students s
    where s.id = p_student_id and s.parent_id = public.current_profile_id()
  ) then
    raise exception 'Only the primary linked parent can remove guardian access.';
  end if;
  delete from public.student_guardians g
  using public.users u
  where g.student_id = p_student_id
    and u.id = g.guardian_profile_id
    and lower(u.email) = lower(btrim(p_guardian_email));
end;
$$;

-- Add a newly reviewed OCR child, or link an existing unclaimed roster row
-- only when all identifying student fields match exactly.
create or replace function public.add_child_to_parent(
  p_student_number text,
  p_student_name text,
  p_grade text,
  p_section text,
  p_academic_year text,
  p_first_name text,
  p_last_name text,
  p_middle_initial text,
  p_gender text
) returns bigint
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  profile_id bigint;
  profile_name text;
  existing_student public.students%rowtype;
  normalized_middle text;
begin
  if auth.uid() is null or public.current_app_role() <> 'parent' then
    raise exception 'Only a signed-in parent can add a linked child.';
  end if;
  if nullif(btrim(p_student_number), '') is null then
    raise exception 'Student number is required.';
  end if;
  if nullif(btrim(p_first_name), '') is null
    or nullif(btrim(p_last_name), '') is null
    or nullif(btrim(p_middle_initial), '') is null
    or nullif(btrim(p_grade), '') is null
    or nullif(btrim(p_section), '') is null
    or nullif(btrim(p_gender), '') is null then
    raise exception 'Complete all student details before linking the child.';
  end if;

  profile_id := public.current_profile_id();
  select u.name into profile_name from public.users u where u.id = profile_id;
  normalized_middle := lower(regexp_replace(btrim(p_middle_initial), '\.$', ''));

  select * into existing_student
  from public.students
  where lrn = btrim(p_student_number)
  for update;

  if found then
    if lower(btrim(coalesce(existing_student.first_name, ''))) <> lower(btrim(p_first_name))
      or lower(btrim(coalesce(existing_student.last_name, ''))) <> lower(btrim(p_last_name))
      or lower(regexp_replace(btrim(coalesce(existing_student.middle_initial, '')), '\.$', '')) <> normalized_middle
      or lower(btrim(coalesce(existing_student.grade, ''))) <> lower(btrim(p_grade))
      or lower(btrim(coalesce(existing_student.section, ''))) <> lower(btrim(p_section))
      or lower(btrim(coalesce(existing_student.gender, ''))) <> lower(btrim(p_gender)) then
      raise exception 'The student number exists with different details. Please check the certificate or contact the school.';
    end if;

    if existing_student.parent_id is not null and existing_student.parent_id <> profile_id then
      raise exception 'This student is already linked to another parent account. Please contact the school office.';
    end if;

    update public.students
    set parent_id = profile_id,
        parent_fullname = profile_name
    where id = existing_student.id;
    return existing_student.id;
  end if;

  insert into public.students (
    parent_id, name, grade, section, academic_year, lrn,
    first_name, last_name, middle_initial, gender, parent_fullname
  ) values (
    profile_id, btrim(p_student_name), btrim(p_grade), btrim(p_section),
    coalesce(nullif(btrim(p_academic_year), ''), ''), btrim(p_student_number),
    btrim(p_first_name), btrim(p_last_name),
    regexp_replace(btrim(p_middle_initial), '\.$', ''), btrim(p_gender), profile_name
  ) returning id into existing_student.id;

  return existing_student.id;
end;
$$;

